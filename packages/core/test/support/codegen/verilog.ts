import { encodeStates, STATE_ENCODINGS } from './encoding.ts';
import type { StateEncoding } from './encoding.ts';
import type { FsmLike, Issue } from './types.ts';
import { validateModel } from './validate.ts';
import type { NormalizedFsm, NormalizedTransition } from './validate.ts';

export type VerilogStyle = 'three-block' | 'two-block';

export const VERILOG_STYLES: readonly VerilogStyle[] = ['three-block', 'two-block'];

export interface VerilogOptions {
  /**
   * 'three-block' (default): state register, next-state logic and output logic
   * in separate always blocks. 'two-block': state register plus one combined
   * combinational block.
   */
  style?: VerilogStyle;
  /** State encoding; default 'binary'. */
  encoding?: StateEncoding;
  /** For encoding 'custom': state id or name -> code such as "101" or "3'b101". */
  customCodes?: Record<string, string>;
  /** Indentation unit; default four spaces. */
  indent?: string;
  /** Leading comment block describing the machine; default true. */
  header?: boolean;
}

export interface VerilogResult {
  /** The generated module, or null when there are errors. */
  code: string | null;
  errors: Issue[];
  warnings: Issue[];
  /** State id -> binary code (MSB first) actually used. Empty on error. */
  stateCodes: Record<string, string>;
}

/**
 * Generate a synthesizable Verilog-2001 module for an FSM model.
 * Never throws for a bad model; problems come back in `errors`.
 */
export function generateVerilog(model: FsmLike, options: VerilogOptions = {}): VerilogResult {
  const style = options.style ?? 'three-block';
  const encoding = options.encoding ?? 'binary';
  const optionErrors: Issue[] = [];
  if (!VERILOG_STYLES.includes(style)) {
    optionErrors.push({ path: 'options.style', message: `style must be one of ${VERILOG_STYLES.join(', ')}` });
  }
  if (!STATE_ENCODINGS.includes(encoding)) {
    optionErrors.push({ path: 'options.encoding', message: `encoding must be one of ${STATE_ENCODINGS.join(', ')}` });
  }

  const { fsm, errors, warnings } = validateModel(model);
  errors.push(...optionErrors);
  if (!fsm || errors.length > 0) return { code: null, errors, warnings, stateCodes: {} };

  let codes: string[];
  let width: number;
  try {
    let custom: string[] | undefined;
    if (encoding === 'custom') {
      const given = options.customCodes ?? {};
      custom = fsm.states.map((s, i) => {
        const code = given[s.id] ?? given[s.label];
        if (code === undefined) {
          errors.push({ path: `options.customCodes`, message: `no code given for state "${s.label}" (states[${i}])` });
          return '0';
        }
        return code;
      });
      if (errors.length > 0) return { code: null, errors, warnings, stateCodes: {} };
    }
    ({ codes, width } = encodeStates(fsm.states.length, encoding, custom));
  } catch (e) {
    errors.push({ path: 'options.customCodes', message: (e as Error).message });
    return { code: null, errors, warnings, stateCodes: {} };
  }

  const code = emit(fsm, { style, encoding, codes, width, indent: options.indent ?? '    ', header: options.header ?? true });
  const stateCodes = Object.fromEntries(fsm.states.map((s, i) => [s.id, codes[i]]));
  return { code, errors, warnings, stateCodes };
}

/** Like generateVerilog, but returns the code and throws if the model has errors. */
export function generateVerilogOrThrow(model: FsmLike, options?: VerilogOptions): string {
  const result = generateVerilog(model, options);
  if (result.code === null) {
    const list = result.errors.map((e) => `  ${e.path ? e.path + ': ' : ''}${e.message}`).join('\n');
    throw new Error(`Cannot generate Verilog:\n${list}`);
  }
  return result.code;
}

interface EmitConfig {
  style: VerilogStyle;
  encoding: StateEncoding;
  codes: string[];
  width: number;
  indent: string;
  header: boolean;
}

function range(width: number): string {
  return width > 1 ? `[${width - 1}:0]` : '';
}

function emit(fsm: NormalizedFsm, cfg: EmitConfig): string {
  const out: string[] = [];
  let depth = 0;
  const line = (text = '') => out.push(text ? cfg.indent.repeat(depth) + text : '');
  const open = (text: string) => {
    line(text);
    depth++;
  };
  const close = (text: string) => {
    depth--;
    line(text);
  };

  const { states, outputs, reset, clock } = fsm;
  const hasMealy = fsm.transitions.some((ts) => ts.some((t) => t.outputs.size > 0));
  const hasMoore = states.some((s) => s.outputs.size > 0);
  const initialParam = states[fsm.initial].param;

  if (cfg.header) {
    const kind = hasMealy ? (hasMoore ? 'Mixed Moore/Mealy' : 'Mealy') : 'Moore';
    line(`// ${fsm.moduleName}: ${kind} FSM, ${states.length} state${states.length === 1 ? '' : 's'}`);
    line(`// Generated by FSM Designer (${cfg.style}, ${cfg.encoding} state encoding). Edit the diagram, not this file.`);
    line(`// Reset: ${reset.name} is ${reset.activeLow ? 'active-low' : 'active-high'}, ${reset.async ? 'asynchronous' : 'synchronous'}; resets to ${initialParam}.`);
    line();
  }
  line('`default_nettype none');
  line();

  // Ports
  const ports: [string, string, string][] = [
    ['input', 'wire', clock],
    ['input', 'wire', reset.name],
    ...fsm.inputs.map((p): [string, string, string] => ['input', `wire${p.width > 1 ? ' ' + range(p.width) : ''}`, p.name]),
    ...outputs.map((p): [string, string, string] => ['output', `reg${p.width > 1 ? ' ' + range(p.width) : ''}`, p.name]),
  ];
  const typeWidth = Math.max(...ports.map((p) => p[1].length));
  open(`module ${fsm.moduleName} (`);
  ports.forEach(([dir, type, name], i) => {
    line(`${dir.padEnd(6)} ${type.padEnd(typeWidth)} ${name}${i < ports.length - 1 ? ',' : ''}`);
  });
  depth--;
  line(');');
  depth++;
  line();

  // State encoding
  const paramWidth = Math.max(...states.map((s) => s.param.length));
  line(`// State encoding (${cfg.encoding})`);
  states.forEach((s, i) => {
    const note = s.label !== s.param.slice(2) || i === fsm.initial ? `  // ${s.label}${i === fsm.initial ? ' (initial)' : ''}` : '';
    line(`localparam ${range(cfg.width) ? range(cfg.width) + ' ' : ''}${s.param.padEnd(paramWidth)} = ${cfg.width}'b${cfg.codes[i]};${note}`);
  });
  line();
  line(`reg ${range(cfg.width) ? range(cfg.width) + ' ' : ''}state, next_state;`);
  line();

  // State register
  const resetActive = reset.activeLow ? `!${reset.name}` : reset.name;
  const sensitivity = reset.async
    ? `posedge ${clock} or ${reset.activeLow ? 'negedge' : 'posedge'} ${reset.name}`
    : `posedge ${clock}`;
  line('// State register');
  open(`always @(${sensitivity}) begin`);
  open(`if (${resetActive})`);
  line(`state <= ${initialParam};`);
  close('else');
  depth++;
  line('state <= next_state;');
  depth--;
  close('end');
  line();

  const assignDefaults = () => {
    for (const o of outputs) line(`${o.name} = ${o.defaultValue};`);
  };
  const assignOutputs = (values: Map<string, string>) => {
    for (const o of outputs) {
      const v = values.get(o.name);
      if (v !== undefined) line(`${o.name} = ${v};`);
    }
  };

  /** Emit an if / else if / else chain over `ts`; `body` writes each branch. */
  const chain = (ts: NormalizedTransition[], body: (t: NormalizedTransition) => void) => {
    // Validation drops anything after an unconditional transition, so an
    // unconditional one is either alone (no if needed) or the final else.
    ts.forEach((t, i) => {
      if (i === 0) {
        if (t.condition === null) {
          body(t);
          return;
        }
        open(`if (${t.condition}) begin`);
      } else {
        depth--;
        line(t.condition === null ? 'end else begin' : `end else if (${t.condition}) begin`);
        depth++;
      }
      body(t);
      if (i === ts.length - 1) close('end');
    });
  };

  const nextState = (t: NormalizedTransition) => line(`next_state = ${states[t.to].param};`);

  if (cfg.style === 'two-block') {
    line('// Next-state and output logic');
    open('always @(*) begin');
    line('next_state = state;');
    assignDefaults();
    open('case (state)');
    states.forEach((s, i) => {
      open(`${s.param}: begin`);
      assignOutputs(s.outputs);
      chain(fsm.transitions[i], (t) => {
        nextState(t);
        assignOutputs(t.outputs);
      });
      close('end');
    });
    open('default: begin');
    line(`next_state = ${initialParam};`);
    close('end');
    close('endcase');
    close('end');
  } else {
    line('// Next-state logic');
    open('always @(*) begin');
    line('next_state = state;');
    open('case (state)');
    states.forEach((s, i) => {
      if (fsm.transitions[i].length === 0) {
        line(`${s.param}: ; // no transitions: stay`);
        return;
      }
      open(`${s.param}: begin`);
      chain(fsm.transitions[i], nextState);
      close('end');
    });
    line(`default: next_state = ${initialParam};`);
    close('endcase');
    close('end');

    if (outputs.length > 0) {
      line();
      line(`// Output logic (${hasMealy ? 'Moore outputs from state, Mealy outputs from state and inputs' : 'Moore: depends on state only'})`);
      open('always @(*) begin');
      assignDefaults();
      open('case (state)');
      states.forEach((s, i) => {
        // Mealy branches must keep the same priority as the next-state chain,
        // so include every transition up to the last one that drives an output.
        const ts = fsm.transitions[i];
        let last = -1;
        ts.forEach((t, k) => {
          if (t.outputs.size > 0) last = k;
        });
        const mealy = ts.slice(0, last + 1);
        if (s.outputs.size === 0 && mealy.length === 0) return;
        open(`${s.param}: begin`);
        assignOutputs(s.outputs);
        chain(mealy, (t) => {
          if (t.outputs.size === 0) line('// outputs keep the values above');
          assignOutputs(t.outputs);
        });
        close('end');
      });
      line('default: ;');
      close('endcase');
      close('end');
    }
  }

  depth = 0;
  line();
  line('endmodule');
  line();
  line('`default_nettype wire');
  return out.join('\n') + '\n';
}
